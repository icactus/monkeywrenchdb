def extract_fn_data(data):
    lines = data.strip().split('\n')
    extracted = []
    for line in lines:
        if '|' in line:
            parts = line.split('|')
            if len(parts) >= 5:
                try:
                    idx = int(parts[0].strip())
                    err_str = parts[2].strip().replace('s', '')
                    error = float(err_str)
                    extracted.append({'idx': idx, 'error': error})
                except:
                    pass
    return extracted

