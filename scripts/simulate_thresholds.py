def extract_rt_data(data):
    lines = data.strip().split('\n')
    extracted = []
    for line in lines:
        if '|' in line:
            parts = line.split('|')
            if len(parts) >= 5:
                idx = int(parts[0].strip())
                conf = parts[2].strip()
                rt_str = parts[4].strip().replace('s', '')
                try:
                    rt = float(rt_str)
                    extracted.append({'idx': idx, 'rt': rt, 'conf_orig': conf})
                except:
                    pass
    return extracted

